<?php

/*
|--------------------------------------------------------------------------
| Сервис формирования текстов согласий на обработку ПДн
|--------------------------------------------------------------------------
|
| Формирует полные тексты согласий на основе конфига оператора и версий.
| Тексты для публичных страниц и для сохранения в БД (дословный текст
| лога) — идентичны; для согласия на распространение текст формируется
| динамически с учётом данных субъекта и дополнительных условий.
|
| Правовая база: ч. 4 ст. 9 и ст. 10.1 Федерального закона № 152-ФЗ,
| Приказ Роскомнадзора № 18 от 24.02.2021.
*/

namespace App\Services;

use Illuminate\Support\Facades\Config;

class ConsentTextBuilder
{
    /*
    | Дата вступления в силу текстов согласий версии 1.0.
    */
    public const CONSENT_EFFECTIVE_DATE = '26 сентября 2026 г.';

    /**
     * Собрать полный текст согласия на обработку персональных данных.
     *
     * @param array{subject_purpose} $data  цель обработки (из конфига/формы)
     * @return array{text: string, version: string}
     */
    public function processingText(array $data = []): array
    {
        $operator     = Config::get('operator');
        $version      = Config::get('consent.versions.processing', '1.0');
        $appName      = config('app.name', '');
        $siteUrl      = $operator['site_url'] ?? '';
        $days         = Config::get('consent.revocation_days', 7);
        $contactUrl   = route('contact');
        $effectiveDate = self::CONSENT_EFFECTIVE_DATE;

        $purpose = $data['subject_purpose'] ?? 'модерация и идентификация комментариев';

        // Собираем перечень данных для обработки.
        $dataList = implode('; ', [
            'имя (никнейм)',
            'адрес электронной почты (e-mail)',
            'адрес IP-адрес',
            'данные сессии и cookie',
            'информация о браузере (пользовательский агент userAgent)',
        ]);

        // Собираем перечень действий.
        $actionsList = implode('; ', [
            'сбор',
            'систематизация',
            'накопление',
            'хранение',
            'уточнение (обновление, изменение)',
            'использование',
            'деперсонализация (обезличивание)',
            'блокирование',
            'удаление',
        ]);

        $text = <<<TEXT
<h2>Согласие на обработку персональных данных</h2>

<p>Настоящим я свободно, своей волей и в своём интересе даю согласие {$appName} (далее — Оператор) на обработку своих персональных данных на следующих условиях:</p>

<h3>1. Персональные данные, которые будут обработаны</h3>
<ul>
    <li>{$dataList};</li>
</ul>

<h3>2. Цели обработки</h3>
<p>{$purpose}.</p>

<h3>3. Перечень действий с данными</h3>
<p>Оператор будет осуществлять следующие действия с данными: {$actionsList}.</p>

<h3>4. Правовое основание</h3>
<p>Обработка осуществляется на основании моего согласия, предусмотренного ч. 4 ст. 9 Федерального закона № 152-ФЗ «О персональных данных».</p>

<h3>5. Срок действия согласия</h3>
<p>Согласие действует с момента его предоставления до момента его отзыва. Обработка осуществляется в течение срока, необходимого для достижения целей обработки, а также в течение {$days} рабочих дней с момента получения Оператором отзыва согласия (если отзыв не предусматривает немедленного удаления).</p>

<h3>6. Передача данных третьим лицам</h3>
<p>Оператор вправе передавать персональные данные третьему лицу — провайдеру хостинга (хостинг-провайдеру) — исключительно для обеспечения функционирования сайта {$siteUrl} при условии, что данное третье лицо принимает на себя обязательства по защите обрабатываемых персональных данных.</p>

<h3>7. Порядок отзыва согласия</h3>
<p>Согласие может быть отозвано путём направления письменного заявления Оператору любым способом, указанным в разделе <a href="{$contactUrl}">«Контакты»</a>, либо через форму обратной связи на сайте. После получения отзыва Оператор прекратит обработку и произведёт удаление (либо обезличивание) персональных данных в сроки, указанные в разделе 5.</p>

<p><small>Версия текста: {$version}. Дата вступления в силу: {$effectiveDate}.</small></p>
TEXT;

        return ['text' => $text, 'version' => $version];
    }

    /**
     * Собрать полный текст согласия на распространение персональных данных.
     *
     * Согласно Приказу РКН № 18: согласие на распространение ПДн должно
     * содержать данные субъекта, цель, перечень данных, «дополнительные
     * условия/запреты», срок и порядок отзыва.
     *
     * @param array{subject_name?: string, conditions?: string} $data данные из формы
     * @return array{text: string, version: string}
     */
    public function distributionText(array $data = []): array
    {
        $operator     = Config::get('operator');
        $version      = Config::get('consent.versions.distribution', '1.0');
        $appName      = config('app.name', '');
        $days         = Config::get('consent.revocation_days', 7);
        // Законный срок прекращения распространения ПДн после отзыва —
        // 3 рабочих дня (ч. 4 ст. 9 Федерального закона № 152-ФЗ).
        $stopDays     = Config::get('consent.distribution.stop_days', 3);
        $contactUrl   = route('contact');
        $effectiveDate = self::CONSENT_EFFECTIVE_DATE;

        $subjectName = $data['subject_name'] ?? '[Имя субъекта]';
        $conditions  = trim($data['conditions'] ?? '');

        $conditionsBlock = '';
        if ($conditions !== '') {
            $conditionsBlock = <<<HTML
<h3>Дополнительные условия и запреты</h3>
<p>Субъект указал следующие дополнительные условия и запреты на обработку:</p>
<blockquote>{$conditions}</blockquote>
HTML;
        } else {
            $conditionsBlock = '<p><strong>Запреты не указаны.</strong></p>';
        }

        $text = <<<TEXT
<h2>Согласие на распространение персональных данных</h2>

<p>Настоящим я, <strong>{$subjectName}</strong>, свободно, своей волей и в своём интересе даю согласие на распространение своих персональных данных {$appName} (далее — Оператор) на следующих условиях:</p>

<h3>1. Цели распространения</h3>
<p>Публикация комментариев на сайте {$appName} (размещение моего имени/никнейма и текста комментария в публичном доступе).</p>

<h3>2. Персональные данные, которые будут распространяться</h3>
<ul>
    <li>имя (никнейм);</li>
    <li>текст комментария.</li>
</ul>

<h3>3. Перечень действий с данными</h3>
<p>Оператор будет осуществлять следующие действия с данными: сбор, систематизация, накопление, хранение, использование, распространение, обезличивание, удаление.</p>

<h3>4. Правовое основание</h3>
<p>Распространение осуществляется на основании моего согласия, предусмотренного ч. 4 ст. 9 и ст. 10.1 Федерального закона № 152-ФЗ «О персональных данных», а также Приказа Роскомнадзора № 18 от 24.02.2021.</p>

<h3>5. Срок действия согласия</h3>
<p>Согласие действует с момента его предоставления до момента его отзыва. Распространение ПДн прекращается в течение {$stopDays} рабочих дней с момента получения Оператором отзыва согласия (ч. 4 ст. 9 Федерального закона № 152-ФЗ), обезличивание комментария производится в течение {$days} рабочих дней.</p>

{$conditionsBlock}

<h3>6. Авторские права</h3>
<p>Я подтверждаю, что текст комментария является моим собственным произведением, и предоставляю Оператору право его использования в соответствии с настоящей Политикой конфиденциальности и настоящим согласием.</p>

<h3>7. Порядок отзыва согласия</h3>
<p>Согласие может быть отозвано путём направления письменного заявления Оператору любым способом, указанным в разделе <a href="{$contactUrl}">«Контакты»</a>, либо через форму обратной связи на сайте. После получения отзыва Оператор прекратит распространение в течение {$stopDays} рабочих дней и произведёт обезличивание (имя будет заменено на «Аноним») в течение {$days} рабочих дней; текст комментария останется опубликованным.</p>

<p><small>Версия текста: {$version}. Дата вступления в силу: {$effectiveDate}.</small></p>
TEXT;

        return ['text' => $text, 'version' => $version];
    }
}
